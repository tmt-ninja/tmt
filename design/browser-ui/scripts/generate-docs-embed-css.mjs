// The hosted docs' stylesheet (#5866): the docs site's own styles, each kept inside the docs'
// element, as one ordinary file. Design loads it as a self-hosted asset, since the Colab owner
// policy admits no inline style. The host already loads the browser-ui tokens and parts.
import { readFile, writeFile } from 'node:fs/promises';
import { scopeCss } from './scope-css.mjs';

const mode = process.argv[2];
if (process.argv.length !== 3 || !['--write', '--check'].includes(mode)) {
  throw new Error('Use --write or --check');
}
export const SCOPE = '.tmt-design-docs';
const sources = [
  '../generated/editorial.css',
  '../gallery/gallery.css',
  '../docs/docs.css',
  '../docs/mock-colab.css',
  '../docs/mock-reader.css',
  '../docs/mock-list.css',
  '../docs/tui/tui.css',
  '../docs/mock-tui/mock-tui.css',
  // Last, so the hosted overrides win over the site's own rules.
  '../docs/hosted.css',
];
const parts = await Promise.all(
  sources.map(async (source) => {
    const css = await readFile(new URL(source, import.meta.url), 'utf8');
    return `/* ${source.slice(3)} */\n${scopeCss(css, SCOPE)}`;
  }),
);
const text = `/* Generated by scripts/generate-docs-embed-css.mjs; do not edit. */\n${parts.join('\n')}`;
const file = new URL('../generated/docs-embed.css', import.meta.url);
if (mode === '--write') await writeFile(file, text);
else if ((await readFile(file, 'utf8').catch(() => '')) !== text)
  throw new Error('Stale generated docs-embed.css: run pnpm generate');
